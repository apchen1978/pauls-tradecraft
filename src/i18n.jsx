// 語言切換時同步 <html lang>、title 與分享用描述（SEO / a11y）。
// 用字跟首頁 hero 對齊：中文「賺不賺得到」；英文 "whether it is profitable"。
const titles = {
  zh: "Paul's Tradecraft｜好產品，值得遇到對的買家",
  en: "Paul's Tradecraft | The right buyer for a good product",
};
const ogDescriptions = {
  zh: "從產品到買家這一段，我陪你一起打通。Paul Chen：15 年國際業務，含中國大陸通路與團隊管理，加上 AI 原生的做法，把找買家、算利潤、談成訂單的判斷做成能試玩的工具。",
  en: "From product to buyer, I'll clear the path with you. Paul Chen: 15 years in international sales, including mainland China channels and team management, plus an AI-native way of working that turns the judgment calls of finding buyers, working out profit and closing orders into tools you can try.",
};

// 首頁可由 `?lang=en` 進入英文版（雙語 demo 的「回作品集」連結會帶此參數）。
// 只讀取、不改寫 URL；任何解析失敗都回退 zh。
function readInitialLang() {
  try {
    return new URLSearchParams(window.location.search).get("lang") === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function LangProvider({ children }) {
  const [lang, setLang] = useState(readInitialLang);
  const t = dict[lang];
  const toggle = () => setLang((l) => (l === "zh" ? "en" : "zh"));

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-Hant" : "en";
    document.title = titles[lang];
    document.querySelector('meta[name="description"]')?.setAttribute("content", ogDescriptions[lang]);
    document.querySelector('meta[property="og:title"]')?.setAttribute("content", titles[lang]);
    document.querySelector('meta[property="og:description"]')?.setAttribute("content", ogDescriptions[lang]);
    document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", titles[lang]);
    document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", ogDescriptions[lang]);
  }, [lang]);

  return (
    <LangContext.Provider value={{ lang, t, toggle }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}

